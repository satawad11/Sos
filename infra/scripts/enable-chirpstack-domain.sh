#!/usr/bin/env bash
# Put the ChirpStack web UI on its own HTTPS domain. Run from infra/.
#
#   sudo bash scripts/enable-chirpstack-domain.sh lns.dmtc.ac.th                 # SOS admin sign-in, from any network
#   sudo bash scripts/enable-chirpstack-domain.sh lns.dmtc.ac.th 202.29.228.0/28 # + also only from these IPs (optional)
#   sudo bash scripts/enable-chirpstack-domain.sh --disable
#
# Access: every request needs an SOS admin session (dashboard > ChirpStack > "เปิดหน้า ChirpStack"; backend app/csgate.py).
# IP/CIDR arguments are an optional EXTRA restriction on top of that — leave them out when staff connect from changing IPs.
# Before: DNS A record of the domain -> this server's public IP, ports 80/443 forwarded (same as the SOS domain).
set -euo pipefail
cd "$(dirname "$0")/.."
SITE=caddy/sites/chirpstack.caddy
mkdir -p caddy/sites
[ -f .env ] || { echo "infra/.env not found — run scripts/init.sh first"; exit 1; }

set_env() {   # set_env KEY VALUE  (adds the line if missing)
  if grep -q "^$1=" .env; then sed -i "s|^$1=.*|$1=$2|" .env; else echo "$1=$2" >> .env; fi
}

if [ "${1:-}" = "--disable" ]; then
  rm -f "$SITE"; set_env CS_DOMAIN ""
  docker compose up -d caddy backend >/dev/null
  docker compose exec -T caddy caddy reload --config /etc/caddy/Caddyfile >/dev/null
  echo "ChirpStack domain disabled (UI is back to SSH tunnel only: ssh -L 8080:localhost:8080 ...)"
  exit 0
fi

DOM="${1:?usage: enable-chirpstack-domain.sh <domain> [allowed CIDR ...] | --disable}"
shift
[[ "$DOM" =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?\.[a-z]{2,}$ ]] || { echo "bad domain: $DOM"; exit 1; }
. ./.env
[ "$DOM" != "${DOMAIN:-}" ] || { echo "use a different domain than the dashboard ($DOMAIN), e.g. lns.${DOMAIN#*.}"; exit 1; }

ALLOW=("$@")                                          # optional; empty = no IP restriction (sign-in only)
for c in "${ALLOW[@]}"; do
  [[ "$c" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$ || "$c" =~ ^[0-9a-fA-F:]+(/[0-9]{1,3})?$ ]] || { echo "bad CIDR: $c"; exit 1; }
done

# Cloudflare edge ranges (https://www.cloudflare.com/ips/) — only used to tell whether the record is proxied.
CF4="173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18 108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17 162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22"
in_cf() { python3 -c 'import ipaddress,sys;a=ipaddress.ip_address(sys.argv[1]);sys.exit(0 if any(a in ipaddress.ip_network(n) for n in sys.argv[2:]) else 1)' "$1" $CF4 2>/dev/null; }

ip="$(getent ahostsv4 "$DOM" | awk 'NR==1{print $1}')" || true
echo "DNS $DOM -> ${ip:-<not found>}   (must be this server's public IP, or Let's Encrypt will fail)"
if [ -n "$ip" ] && in_cf "$ip"; then
  echo "note: $DOM points to Cloudflare ($ip) — the record is proxied (orange cloud)."
  echo "      That works: the allow-list checks the visitor's IP that Cloudflare forwards (CF-Connecting-IP)."
  echo "      'DNS only' (grey cloud) like ${DOMAIN:-the dashboard domain} is simpler and avoids Cloudflare timeouts."
fi

IPBLOCK=""
if [ ${#ALLOW[@]} -gt 0 ]; then   # client_ip = the visitor, also behind Cloudflare's proxy (trusted_proxies in the main Caddyfile)
  IPBLOCK=$(printf '\t\t@outside not client_ip %s\n\t\trespond @outside "403 — IP {client_ip} is not in the extra IP list of this site. Run enable-chirpstack-domain.sh again without IPs to allow every network (SOS admin sign-in still required)." 403\n' "${ALLOW[*]}")
  IPBLOCK+=$'\n'
fi

cat > "$SITE" <<EOF
# generated by scripts/enable-chirpstack-domain.sh — ChirpStack admin UI
$DOM {
	encode gzip
	header {
		Strict-Transport-Security "max-age=31536000"
		X-Content-Type-Options nosniff
		# not no-referrer: map tiles need an origin. Cross-site requests get only https://<domain>, never a path.
		Referrer-Policy strict-origin-when-cross-origin
	}
	# route = run in exactly this order: (optional IP list) -> sign-in pages -> SOS admin session check -> everything else.
	route {
${IPBLOCK}		# One-time sign-in link from the dashboard, and sign-out (backend app/csgate.py). Nothing else of the backend is exposed here.
		@gate path /__sos/login /__sos/logout
		handle @gate {
			uri replace /__sos/ /api/cs-gate/ 1
			reverse_proxy backend:8000
		}
		# Every other request needs a valid SOS admin session cookie (sos_cs). Not signed in -> page linking to the dashboard.
		forward_auth backend:8000 {
			uri /api/cs-gate/check
			copy_headers X-SOS-User
		}
		# Gateway-map tiles (chirpstack.toml [ui] tileserver="/osm-tiles/..."): fetched by the server and identified as this
		# system, per the OSM tile usage policy — OSM blocks the tile requests ChirpStack's UI makes from the browser.
		handle_path /osm-tiles/* {
			@tile path_regexp ^/[0-9]+/[0-9]+/[0-9]+\.png$
			handle @tile {
				reverse_proxy https://tile.openstreetmap.org {
					header_up Host tile.openstreetmap.org
					header_up User-Agent "SOS-emergency-button/1.0 (ChirpStack gateway map; https://$DOM)"
					header_up Referer "https://$DOM/"
					header_up -Cookie
					header_up -Authorization
					header_down Cache-Control "public, max-age=604800"
				}
			}
			respond 404
		}
		reverse_proxy chirpstack:8080 {
			flush_interval -1
		}
	}
}
EOF
set_env CS_DOMAIN "$DOM"

docker compose up -d caddy backend >/dev/null       # caddy: mounts caddy/sites · backend: shows the link on the ChirpStack page
if ! docker compose exec -T caddy caddy validate --adapter caddyfile --config /etc/caddy/Caddyfile >/tmp/caddy-validate.log 2>&1; then
  echo "Caddy rejected the new site — rolled back. Details:"; tail -5 /tmp/caddy-validate.log
  rm -f "$SITE"; set_env CS_DOMAIN ""; docker compose up -d backend >/dev/null; exit 1
fi
docker compose exec -T caddy caddy reload --config /etc/caddy/Caddyfile >/dev/null
echo
echo "ChirpStack UI : https://$DOM"
echo "Open it from  : SOS dashboard > ChirpStack > \"เปิดหน้า ChirpStack\"  (SOS admin sign-in, any network)"
[ ${#ALLOW[@]} -eq 0 ] || echo "Extra IP list : ${ALLOW[*]}"
echo "First login is admin/admin if never changed — CHANGE IT NOW (top-right menu > Change password)."
echo "Disable again : sudo bash scripts/enable-chirpstack-domain.sh --disable"
